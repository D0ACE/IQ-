class LoginForm extends StatefulWidget {
  final int selectedRole;
  const LoginForm({super.key, required this.selectedRole});

  @override
  State<LoginForm> createState() => _LoginFormState();
}

class _LoginFormState extends State<LoginForm> {
  final TextEditingController passwordController = TextEditingController();
  final TextEditingController emailController = TextEditingController();
  final GlobalKey<FormState> _formKey = GlobalKey<FormState>();

  final List<String> roles = [
    'Super Admin',
    'Admin',
    'Consultant',
    'Customer',
  ];

  @override
  void dispose() {
    emailController.dispose();
    passwordController.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return BlocProvider(
      create: (_) => getIt<AuthCubit>(),
      child: BlocListener<AuthCubit, AuthState>(
        listener: (context, state) {
          if (state is AuthSuccess) {
            // if (state.roleId == "1") {
            //   // Admin dashboard
            //   GoRouter.of(context).go(AppRoutes.adminDashboard);
            // } else if (state.roleId == "2") {
            //   // Consultant dashboard
            //   GoRouter.of(context).go(AppRoutes.consultantDashboard);
            // } else if (state.roleName == AppConst.isAutoGeneratedPassCustomer) {
            //   // Force password change
            //   showChangePasswordDialog(context, state.roleId);
            // } else if (state.roleName == AppConst.isCustomer) {
            //   // Customer dashboard
            //   GoRouter.of(context).go(AppRoutes.customerDashboard);
            // }
            if (state.roleId == "0") {
              // ✅ SUPER ADMIN dashboard
              GoRouter.of(context).go(AppRoutes.superAdminDashboard);
            } else if (state.roleId == "1") {
              // Admin dashboard
              GoRouter.of(context).go(AppRoutes.adminDashboard);
            } else if (state.roleId == "2") {
              // Consultant dashboard
              GoRouter.of(context).go(AppRoutes.consultantDashboard);
            } else if (state.roleName == AppConst.isAutoGeneratedPassCustomer) {
              // Force password change for customer
              showChangePasswordDialog(context, state.customerId, isEmployee: false);
            } else if (state.roleName == AppConst.isAutoGeneratedPassEmployee) {
              // Force password change for employee
              showChangePasswordDialog(context, state.customerId, isEmployee: true);
            } else if (state.roleName == AppConst.isCustomer) {
              // Customer dashboard
              GoRouter.of(context).go(AppRoutes.customerDashboard);
            } else if (state.roleName == AppConst.isEmployee) {
              // Employee dashboard
              GoRouter.of(context).go(AppRoutes.employeeDashboard);
            }
          }

          if (state is AuthFailure) {
            ScaffoldMessenger.of(
              context,
            ).showSnackBar(SnackBar(content: Text(state.message)));
          }
        },
        child: _buildForm(context),
      ),
    );
  }

  Widget _buildForm(BuildContext context) {
    return Form(
      key: _formKey,
      child: AnimatedSize(
        duration: const Duration(milliseconds: 300),
        curve: Curves.easeInOut,
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          AnimatedSwitcher(
            duration: const Duration(milliseconds: 300),
            child: Column(
              key: ValueKey('header_${widget.selectedRole}'),
              crossAxisAlignment: CrossAxisAlignment.stretch,
              children: [
                Text(
                  "Welcome back!",
                  textAlign: TextAlign.left,
                  style: TextStyle(
                    fontSize: 28,
                    fontWeight: FontWeight.w900,
                    color: AppColors.kPrimaryColor,
                    letterSpacing: -0.5,
                  ),
                ),
                const SizedBox(height: 8),
                Text(
                  "Sign in as ${roles[widget.selectedRole]} to continue",
                  style: TextStyle(
                    fontSize: 14,
                    color: Colors.grey.shade500,
                    fontWeight: FontWeight.w500,
                  ),
                ),
              ],
            ),
          ),
          const SizedBox(height: 35),
          
          // Email field
          _buildInputLabel("Email Address"),
          const SizedBox(height: 8),
          AppTextFieldWidget(
            keyboardType: TextInputType.emailAddress,
            hintText: "name@company.com",
            textFieldController: emailController,
            validator: AppValidation.checkEmailValidation,
            prefixIconWidget: const Icon(
              Icons.alternate_email_rounded,
              color: AppColors.kPrimaryColor,
              size: 20,
            ),
            contentPadding: const EdgeInsets.symmetric(vertical: 18, horizontal: 20),
            decoration: InputDecoration(
              filled: true,
              fillColor: Colors.grey.shade50,
              hintStyle: TextStyle(color: Colors.grey.shade400, fontSize: 14),
              border: OutlineInputBorder(
                borderRadius: BorderRadius.circular(12),
                borderSide: BorderSide(color: Colors.grey.shade200),
              ),
              enabledBorder: OutlineInputBorder(
                borderRadius: BorderRadius.circular(12),
                borderSide: BorderSide(color: Colors.grey.shade200),
              ),
              focusedBorder: OutlineInputBorder(
                borderRadius: BorderRadius.circular(12),
                borderSide: const BorderSide(color: AppColors.kPrimaryColor, width: 2),
              ),
            ),
          ),

          const SizedBox(height: 20),

          // Password field
          _buildInputLabel("Password"),
          const SizedBox(height: 8),
          AppTextFieldWidget(
            hintText: "••••••••",
            validator: AppValidation.currentPasswordValidator,
            inputFormatters: [LengthLimitingTextInputFormatter(20)],
            textFieldController: passwordController,
            prefixIconWidget: const Icon(
              Icons.lock_outline_rounded,
              color: AppColors.kPrimaryColor,
              size: 20,
            ),
            contentPadding: const EdgeInsets.symmetric(vertical: 18, horizontal: 20),
            isPasswordTextField: true,
            disableFocusBorder: true,
            decoration: InputDecoration(
              filled: true,
              fillColor: Colors.grey.shade50,
              hintStyle: TextStyle(color: Colors.grey.shade400, fontSize: 14),
              border: OutlineInputBorder(
                borderRadius: BorderRadius.circular(12),
                borderSide: BorderSide(color: Colors.grey.shade200),
              ),
              enabledBorder: OutlineInputBorder(
                borderRadius: BorderRadius.circular(12),
                borderSide: BorderSide(color: Colors.grey.shade200),
              ),
              focusedBorder: OutlineInputBorder(
                borderRadius: BorderRadius.circular(12),
                borderSide: const BorderSide(color: AppColors.kPrimaryColor, width: 2),
              ),
            ),
          ),

          Align(
            alignment: Alignment.centerRight,
            child: TextButton(
              onPressed: () {},
              style: TextButton.styleFrom(
                foregroundColor: Colors.grey.shade600,
                padding: EdgeInsets.zero,
                minimumSize: const Size(0, 30),
                tapTargetSize: MaterialTapTargetSize.shrinkWrap,
              ),
              child: const Text(
                "Forgot Password?",
                style: TextStyle(fontSize: 13, fontWeight: FontWeight.w600),
              ),
            ),
          ),

          const SizedBox(height: 25),

          BlocBuilder<AuthCubit, AuthState>(
            builder: (context, state) {
              return SizedBox(
                height: 55,
                child: GradientButton(
                  text: state is AuthLoading ? "Verifying..." : "Sign In",
                  onPressed: state is AuthLoading
                      ? () {}
                      : () => onTapContinue(context),
                  radiusSize: 12,
                ),
              );
            },
          ),

          const SizedBox(height: 25),

          AnimatedSwitcher(
            duration: const Duration(milliseconds: 300),
            transitionBuilder: (Widget child, Animation<double> animation) {
              return FadeTransition(
                opacity: animation,
                child: SlideTransition(
                  position: Tween<Offset>(
                    begin: const Offset(0, 0.1),
                    end: Offset.zero,
                  ).animate(animation),
                  child: child,
                ),
              );
            },
            child: widget.selectedRole == 3 // ✅ CUSTOMER ONLY
                ? Column(
                    key: const ValueKey('customer_extra'),
                    children: [
                      Row(
                        children: [
                          Expanded(child: Divider(color: Colors.grey.shade200)),
                          Padding(
                            padding: const EdgeInsets.symmetric(horizontal: 16),
                            child: Text(
                              "NEW HERE?",
                              style: TextStyle(
                                color: Colors.grey.shade400,
                                fontSize: 10,
                                fontWeight: FontWeight.bold,
                                letterSpacing: 1,
                              ),
                            ),
                          ),
                          Expanded(child: Divider(color: Colors.grey.shade200)),
                        ],
                      ),
                      const SizedBox(height: 20),
                      AlreadyHaveAnAccountCheck(
                        login: true,
                        press: () {
                          GoRouter.of(context).push(
                            AppRoutes.customerOnboarding,
                            extra: OnboardingMode.create,
                          );
                        },
                      ),
                    ],
                  )
                : const SizedBox.shrink(key: ValueKey('empty_extra')),
          ),
        ],
      ),
    ),
  );
}

  Widget _buildInputLabel(String label) {
    return Text(
      label,
      style: const TextStyle(
        fontSize: 13,
        fontWeight: FontWeight.bold,
        color: AppColors.titleText,
      ),
    );
  }

  void onTapContinue(BuildContext context) {
    if (_formKey.currentState!.validate()) {
      context.read<AuthCubit>().login(
        emailController.text.trim(),
        passwordController.text.trim(),
        widget.selectedRole,
      );
    }
  }

  void showChangePasswordDialog(BuildContext context, String customerId, {bool isEmployee = false}) {
    showDialog(
      context: context,
      barrierDismissible: false,
      builder: (_) {
        return BlocProvider(
          create: (_) =>
              CustomerPasswordCubit(AuthRepository(FirebaseFirestore.instance)),
          child: ChangePasswordDialog(customerId: customerId, isEmployee: isEmployee),
        );
      },
    );
  }
}
