class LoginForm extends StatefulWidget {
  final int selectedRole;
  const LoginForm({super.key, required this.selectedRole});

  @override
  State<LoginForm> createState() => _LoginFormState();
}

class _LoginFormState extends State<LoginForm> {
  final TextEditingController passwordController = TextEditingController();
  final TextEditingController emailController = TextEditingController();
  final GlobalKey<FormState> _formKey = GlobalKey<FormState>();

  @override
  void dispose() {
    emailController.dispose();
    passwordController.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return BlocProvider(
      create: (_) => getIt<AuthCubit>(),
      child: BlocListener<AuthCubit, AuthState>(
        listener: (context, state) {
          if (state is AuthSuccess) {
            // if (state.roleId == "1") {
            //   // Admin dashboard
            //   GoRouter.of(context).go(AppRoutes.adminDashboard);
            // } else if (state.roleId == "2") {
            //   // Consultant dashboard
            //   GoRouter.of(context).go(AppRoutes.consultantDashboard);
            // } else if (state.roleName == AppConst.isAutoGeneratedPassCustomer) {
            //   // Force password change
            //   showChangePasswordDialog(context, state.roleId);
            // } else if (state.roleName == AppConst.isCustomer) {
            //   // Customer dashboard
            //   GoRouter.of(context).go(AppRoutes.customerDashboard);
            // }
            if (state.roleId == "0") {
              // ✅ SUPER ADMIN dashboard
              GoRouter.of(context).go(AppRoutes.superAdminDashboard);
            } else if (state.roleId == "1") {
              // Admin dashboard
              GoRouter.of(context).go(AppRoutes.adminDashboard);
            } else if (state.roleId == "2") {
              // Consultant dashboard
              GoRouter.of(context).go(AppRoutes.consultantDashboard);
            } else if (state.roleName == AppConst.isAutoGeneratedPassCustomer) {
              // Force password change for customer
              showChangePasswordDialog(context, state.customerId, isEmployee: false);
            } else if (state.roleName == AppConst.isAutoGeneratedPassEmployee) {
              // Force password change for employee
              showChangePasswordDialog(context, state.customerId, isEmployee: true);
            } else if (state.roleName == AppConst.isCustomer) {
              // Customer dashboard
              GoRouter.of(context).go(AppRoutes.customerDashboard);
            } else if (state.roleName == AppConst.isEmployee) {
              // Employee dashboard
              GoRouter.of(context).go(AppRoutes.employeeDashboard);
            }
          }

          if (state is AuthFailure) {
            ScaffoldMessenger.of(
              context,
            ).showSnackBar(SnackBar(content: Text(state.message)));
          }
        },
        child: _buildForm(context),
      ),
    );
  }

  Widget _buildForm(BuildContext context) {
    return Form(
      key: _formKey,
      child: Column(
        children: [
          AppTextFieldWidget(
            keyboardType: TextInputType.emailAddress,
            hintText: "Your email",
            textFieldController: emailController,
            validator: AppValidation.checkEmailValidation,
            prefixIconWidget: Padding(
              padding: EdgeInsets.all(defaultPadding),
              child: Icon(
                Icons.person,
                color: AppColors.kPrimaryColor,
                size: 23,
              ),
            ),
            contentPadding: const EdgeInsets.fromLTRB(10, 17, 10, 17),
            decoration: const InputDecoration(),
          ),

          Padding(
            padding: const EdgeInsets.symmetric(vertical: defaultPadding),
            child: AppTextFieldWidget(
              hintText: "Your Password",
              validator: AppValidation.currentPasswordValidator,
              inputFormatters: [LengthLimitingTextInputFormatter(20)],
              textFieldController: passwordController,
              prefixIconWidget: Padding(
                padding: EdgeInsets.all(defaultPadding),
                child: Icon(
                  Icons.lock,
                  color: AppColors.kPrimaryColor,
                  size: 23,
                ),
              ),
              contentPadding: const EdgeInsets.fromLTRB(10, 17, 10, 17),
              isPasswordTextField: true,
              disableFocusBorder: true,
              decoration: const InputDecoration(),
            ),
          ),

          Align(
            alignment: Alignment.centerRight,
            child: TextButton(
              onPressed: () {},
              child: Text(
                "Forgot Your Password?",
                style: TextStyle(color: AppColors.kPrimaryColor),
              ),
            ),
          ),

          const SizedBox(height: 20),

          Padding(
            padding: const EdgeInsets.symmetric(vertical: 15),
            child: BlocBuilder<AuthCubit, AuthState>(
              builder: (context, state) {
                return GradientButton(
                  text: state is AuthLoading ? "Please wait..." : "Login",
                  onPressed: state is AuthLoading
                      ? () {}
                      : () => onTapContinue(context),
                  radiusSize: 50,
                );
              },
            ),
          ),

          const SizedBox(height: defaultPadding),

          if (widget.selectedRole == 3) // ✅ CUSTOMER ONLY
            AlreadyHaveAnAccountCheck(
              login: true,
              press: () {
                GoRouter.of(context).push(
                  AppRoutes.customerOnboarding,
                  extra: OnboardingMode.create, // pass mode via extra
                );
              },
            ),
        ],
      ),
    );
  }

  void onTapContinue(BuildContext context) {
    if (_formKey.currentState!.validate()) {
      context.read<AuthCubit>().login(
        emailController.text.trim(),
        passwordController.text.trim(),
        widget.selectedRole,
      );
    }
  }

  void showChangePasswordDialog(BuildContext context, String customerId, {bool isEmployee = false}) {
    showDialog(
      context: context,
      barrierDismissible: false,
      builder: (_) {
        return BlocProvider(
          create: (_) =>
              CustomerPasswordCubit(AuthRepository(FirebaseFirestore.instance)),
          child: ChangePasswordDialog(customerId: customerId, isEmployee: isEmployee),
        );
      },
    );
  }
}
