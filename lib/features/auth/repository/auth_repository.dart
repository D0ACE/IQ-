  final FirebaseFirestore firestore;

  AuthRepository(this.firestore);

  /// LOGIN (Firestore based)
  Future<RoleModel> login(
    String email,
    String password,
    int selectedRole,
  ) async {
    final hiveService = getIt<HiveService>();

    // 1. Try checking the main "users" collection (Admins, Consultants, etc.)
    final userQuery = await firestore
        .collection('users')
        .where('email', isEqualTo: email)
        .where('password', isEqualTo: password)
        .limit(1)
        .get();

    if (userQuery.docs.isNotEmpty) {
      final doc = userQuery.docs.first;
      final data = doc.data();

      if (data['blockStatus'] == true) {
        throw Exception("Your account is blocked. Please contact the administrator.");
      }

      await hiveService.saveUser(
        UserModel(
          userId: doc.id,
          userName: data['userName'],
          email: data['email'],
          phoneNumber: data['phoneNumber'],
          password: data['password'],
          roleId: data['roleId'],
          activeUser: data['activeUser'] ?? true,
          blockStatus: data['blockStatus'] ?? false,
          fcmToken: data['fcmToken'] ?? '',
          createdAt: data['createdAt'] != null 
              ? (data['createdAt'] as Timestamp).toDate() 
              : DateTime.now(),
          customerId: data['customerId'],
        ),
      );

      return RoleModel(id: data['roleId'].toString(), name: data['userName'], customerId: doc.id);
    }

    // 2. Try checking the "employees" sub-collections using Collection Group
    try {
      final employeeQuery = await firestore
          .collectionGroup('employees')
          .where('email', isEqualTo: email)
          .where('password', isEqualTo: password)
          .limit(1)
          .get();

      if (employeeQuery.docs.isNotEmpty) {
        final doc = employeeQuery.docs.first;
        final data = doc.data();

        if (data['blockStatus'] == true) {
          throw Exception("Your account is blocked. Please contact the administrator.");
        }

        await hiveService.saveUser(
          UserModel(
            userId: doc.id,
            userName: data['userName'],
            email: data['email'],
            phoneNumber: data['phoneNumber'] ?? '',
            password: data['password'],
            roleId: data['roleId'] ?? AppConst.employeeRole,
            activeUser: data['activeUser'] ?? true,
            blockStatus: data['blockStatus'] ?? false,
            fcmToken: data['fcmToken'] ?? '',
            createdAt: data['createdAt'] != null 
                ? (data['createdAt'] as Timestamp).toDate() 
                : DateTime.now(),
            customerId: data['customerId'],
          ),
        );

        // Check if it's an auto-generated password for an employee
        if ((data['password'] ?? "").startsWith(AppConst.autoGeneratedPasswordBase)) {
          return RoleModel(
            id: data['roleId'] ?? AppConst.employeeRole,
            name: AppConst.isAutoGeneratedPassEmployee,
            customerId: doc.id,
          );
        }

        return RoleModel(
          id: data['roleId'] ?? AppConst.employeeRole,
          name: AppConst.isEmployee,
          customerId: doc.id,
        );
      }
    } catch (e) {
      developer.log("Employee Login Check Error: $e");
      // Continue to customer check if this fails
    }

    // 3. Try checking the "customers" collection
    final customerQuery = await firestore
        .collection('customers')
        .where('email', isEqualTo: email)
        .where('password', isEqualTo: password)
        .limit(1)
        .get();

    if (customerQuery.docs.isNotEmpty) {
      final doc = customerQuery.docs.first;
      final data = doc.data();

      // 🚫 Check if blocked
      if (data['blockStatus'] == true) {
        throw Exception("Your account is blocked. Please contact the administrator.");
      }

      final approved = data['isProfileApproved'] as bool? ?? false;

      if (!approved) {
        throw Exception("Profile not approved by admin");
      }
      
      await hiveService.saveCustomer(
        CustomerModel.fromJson(data, customerId: doc.id),
      );

      if ((data['password'] ?? "").startsWith(AppConst.autoGeneratedPasswordBase)) {
        return RoleModel(
          id: data['roleId'] ?? '',
          name: AppConst.isAutoGeneratedPassCustomer,
          customerId: doc.id
        );
      } else {
        return RoleModel(id: data['roleId'] ?? '', name: AppConst.isCustomer, customerId: doc.id);
      }
    }

    throw Exception("Invalid email or password");
  }

  /// GET ALL CUSTOMERS
  Future<List<CustomerModel>> getAllCustomers() async {
    final snapshot = await firestore.collection('customers').get();

    final customers = snapshot.docs
        .map((doc) => CustomerModel.fromJson(doc.data(), customerId: doc.id))
        .where((c) => c.companyName.trim().isNotEmpty)
        .toList();

    customers.sort((a, b) => b.createdAt.compareTo(a.createdAt));
    return customers;
  }

  Future<List<CustomerModel>> getFetchAllApprovedCustomers() async {
    final snapshot = await firestore
        .collection('customers')
        .where('isProfileApproved', isEqualTo: true)
        .get();

    final customers = snapshot.docs
        .map((doc) => CustomerModel.fromJson(doc.data(), customerId: doc.id))
        .where((c) => c.companyName.trim().isNotEmpty)
        .toList();

    customers.sort((a, b) => b.createdAt.compareTo(a.createdAt));
    return customers;
  }

