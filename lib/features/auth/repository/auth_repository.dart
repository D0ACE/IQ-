import 'package:iq_plus/features/auth/model/role_model.dart';
import 'package:iq_plus/features/auth/model/user_model.dart';
import 'package:iq_plus/features/auth/model/consultant_user_model.dart';

class AuthRepository {
  final FirebaseFirestore firestore;

  AuthRepository(this.firestore);

  /// LOGIN (Firestore based)
  Future<RoleModel> login(
    String email,
    String password,
    int selectedRole,
  ) async {
    final hiveService = getIt<HiveService>();

    // 1. Try checking the main "users" collection (Admins, Consultants, etc.)
    final userQuery = await firestore
        .collection('users')
        .where('email', isEqualTo: email)
        .where('password', isEqualTo: password)
        .limit(1)
        .get();

    if (userQuery.docs.isNotEmpty) {
      final doc = userQuery.docs.first;
      final data = doc.data();

      if (data['blockStatus'] == true) {
        throw Exception("Your account is blocked. Please contact the administrator.");
      }

      await hiveService.saveUser(
        UserModel(
          userId: doc.id,
          userName: data['userName'],
          email: data['email'],
          phoneNumber: data['phoneNumber'],
          password: data['password'],
          roleId: data['roleId'],
          activeUser: data['activeUser'] ?? true,
          blockStatus: data['blockStatus'] ?? false,
          fcmToken: data['fcmToken'] ?? '',
          createdAt: data['createdAt'] != null 
              ? (data['createdAt'] as Timestamp).toDate() 
              : DateTime.now(),
          customerId: data['customerId'],
        ),
      );

      return RoleModel(id: data['roleId'].toString(), name: data['userName'], customerId: doc.id);
    }

    // 2. Try checking the "employees" sub-collections using Collection Group
    try {
      final employeeQuery = await firestore
          .collectionGroup('employees')
          .where('email', isEqualTo: email)
          .where('password', isEqualTo: password)
          .limit(1)
          .get();

      if (employeeQuery.docs.isNotEmpty) {
        final doc = employeeQuery.docs.first;
        final data = doc.data();

        if (data['blockStatus'] == true) {
          throw Exception("Your account is blocked. Please contact the administrator.");
        }

        await hiveService.saveUser(
          UserModel(
            userId: doc.id,
            userName: data['userName'],
            email: data['email'],
            phoneNumber: data['phoneNumber'] ?? '',
            password: data['password'],
            roleId: data['roleId'] ?? AppConst.employeeRole,
            activeUser: data['activeUser'] ?? true,
            blockStatus: data['blockStatus'] ?? false,
            fcmToken: data['fcmToken'] ?? '',
            createdAt: data['createdAt'] != null 
                ? (data['createdAt'] as Timestamp).toDate() 
                : DateTime.now(),
            customerId: data['customerId'],
          ),
        );

        // Check if it's an auto-generated password for an employee
        if ((data['password'] ?? "").startsWith(AppConst.autoGeneratedPasswordBase)) {
          return RoleModel(
            id: data['roleId'] ?? AppConst.employeeRole,
            name: AppConst.isAutoGeneratedPassEmployee,
            customerId: doc.id,
          );
        }

        return RoleModel(
          id: data['roleId'] ?? AppConst.employeeRole,
          name: AppConst.isEmployee,
          customerId: doc.id,
        );
      }
    } catch (e) {
      developer.log("Employee Login Check Error: $e");
      // Continue to customer check if this fails
    }

    // 3. Try checking the "customers" collection
    final customerQuery = await firestore
        .collection('customers')
        .where('email', isEqualTo: email)
        .where('password', isEqualTo: password)
        .limit(1)
        .get();

    if (customerQuery.docs.isNotEmpty) {
      final doc = customerQuery.docs.first;
      final data = doc.data();

      // 🚫 Check if blocked
      if (data['blockStatus'] == true) {
        throw Exception("Your account is blocked. Please contact the administrator.");
      }

      final approved = data['isProfileApproved'] as bool? ?? false;

      if (!approved) {
        throw Exception("Profile not approved by admin");
      }
      
      await hiveService.saveCustomer(
        CustomerModel.fromJson(data, customerId: doc.id),
      );

      if ((data['password'] ?? "").startsWith(AppConst.autoGeneratedPasswordBase)) {
        return RoleModel(
          id: data['roleId'] ?? '',
          name: AppConst.isAutoGeneratedPassCustomer,
          customerId: doc.id
        );
      } else {
        return RoleModel(id: data['roleId'] ?? '', name: AppConst.isCustomer, customerId: doc.id);
      }
    }

    throw Exception("Invalid email or password");
  }

  /// GET ALL CUSTOMERS
  Future<List<CustomerModel>> getAllCustomers() async {
    final snapshot = await firestore
        .collection('customers')
        .orderBy('createdAt', descending: true)
        .get();

    return snapshot.docs.map((doc) {
      return CustomerModel.fromJson(doc.data(), customerId: doc.id);
    }).toList();
  }

  Future<List<CustomerModel>> getFetchAllApprovedCustomers() async {
    final snapshot = await firestore
        .collection('customers')
        .where('isProfileApproved', isEqualTo: true)
        .get();

    return snapshot.docs.map((doc) {
      return CustomerModel.fromJson(doc.data(), customerId: doc.id);
    }).toList();
  }

  Future<List<CustomerModel>> getFetchConsultantCustomers(
    String? consultantId,
  ) async {
    final snapshot = await firestore
        .collection('customers')
        .where('consultantId', isEqualTo: consultantId)
        .get();

    return snapshot.docs.map((doc) {
      return CustomerModel.fromJson(doc.data(), customerId: doc.id);
    }).toList();
  }

  Future<List<CustomerModel>> getFetchAssignCustomers(
    String consultantId,
  ) async {
    final snapshot = await firestore
        .collection('customers')
        .where('consultantId', isEqualTo: consultantId)
        .get();

    return snapshot.docs.map((doc) {
      return CustomerModel.fromJson(doc.data(), customerId: doc.id);
    }).toList();
  }

  /// APPROVE CUSTOMER
  Future<void> approveCustomer({
    required String customerId,
    required String companyName,
    required String customerEmail,
    required String consultantId,
  }) async {
    final hiveService = getIt<HiveService>();
    UserModel? adminUserModel = hiveService.getUser();
    ConsultantUserModel consultantUserModel = await getConsultantById(
      consultantId,
    );
    final autoGeneratePassword = Utility.autoGeneratePassword();
    await firestore.collection('customers').doc(customerId).update({
      "isProfileApproved": true,
      "password": autoGeneratePassword,
      "approvedByUserId": adminUserModel?.userId,
      "consultantId": consultantUserModel.userId,
      "approvedAt": FieldValue.serverTimestamp(),
    });
    // Send approval email
    await BrevoEmailService.sendCustomerApprovedMail(
      companyName: companyName,
      email: customerEmail,
      password: autoGeneratePassword,
    );
  }

  Future<ConsultantUserModel> getConsultantById(String consultantId) async {
    final doc = await firestore.collection('users').doc(consultantId).get();

    if (!doc.exists) {
      throw Exception("Consultant not found");
    }

    final data = doc.data()!;

    if (data['roleId'] != '2') {
      throw Exception("User is not a consultant");
    }

    return ConsultantUserModel.fromFirestore(doc.id, data);
  }

  Future<CustomerModel?> getCustomerById(String customerId) async {
    final doc = await firestore.collection('customers').doc(customerId).get();
    if (!doc.exists) return null;
    return CustomerModel.fromJson(doc.data()!, customerId: doc.id);
  }

  Future<void> updateCustomerPassword({
    required String customerId,
    required String newPassword,
    bool isEmployee = false,
  }) async {
    if (isEmployee) {
      // Find employee document path via collection group
      final snap = await firestore
          .collectionGroup('employees')
          .get();
      final doc = snap.docs.firstWhere((d) => d.id == customerId);
      await doc.reference.update({
        "password": newPassword,
        "updatedAt": FieldValue.serverTimestamp(),
      });
    } else {
      await firestore.collection('customers').doc(customerId).update({
        "password": newPassword,
        "updatedAt": FieldValue.serverTimestamp(),
      });
    }
  }

  Future<void> updateCustomerNextVisitDate({
    required String customerId,
    required String nextVisitDate,
  }) async {
    await firestore.collection('customers').doc(customerId).update({
      'nextVisitDate': nextVisitDate, // ✅ stored as STRING
    });
  }

  /// ➕ CREATE CUSTOMER
  Future<void> createCustomer(CustomerModel customer) async {
    final Map<String, dynamic> data = customer.toJson();
    data.remove('customerId'); // Firestore will generate it
    await firestore.collection('customers').add(data);
  }

  /// 🔁 UPDATE CUSTOMER
  Future<void> updateCustomer(CustomerModel customer) async {
    await firestore
        .collection('customers')
        .doc(customer.customerId)
        .update(customer.toJson());
  }

  /// ❌ DELETE CUSTOMER
  Future<void> deleteCustomer(String customerId) async {
    await firestore.collection('customers').doc(customerId).delete();
  }
}
