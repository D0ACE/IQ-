/// utils class which contains all utility methods
class Utility {
  /// to change the status bar color black
  static void statusBarColorForHomeGround() {
    WidgetsFlutterBinding.ensureInitialized();
    Platform.isIOS
        ? SystemChrome.setSystemUIOverlayStyle(
            SystemUiOverlayStyle.dark.copyWith(),
          )
        : SystemChrome.setSystemUIOverlayStyle(
            SystemUiOverlayStyle.light.copyWith(
              systemNavigationBarColor: Colors.black,
              systemNavigationBarIconBrightness: Brightness.light,
              statusBarColor: Colors.black, //Android
              statusBarIconBrightness: Brightness.light,
            ),
          );
  }

  static String getRoleNameLogin(int selectedIndex) {
    switch (selectedIndex) {
      case 0:
        return 'Admin';
      case 1:
        return 'Consultant';
      case 2:
        return 'Customer';
      default:
        return 'Unknown';
    }
  }

  /// email validation check fro sign up
  static bool emailValidationPattern({required String value}) {
    String pattern =
        r'^(([^<>()[\]\\.,;:\s@\"]+(\.[^<>()[\]\\.,;:\s@\"]+)*)|(\".+\"))@((\[[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\])|(([a-zA-Z\-0-9]+\.)+[a-zA-Z]{2,}))$';
    RegExp regExp = RegExp(pattern);
    return !regExp.hasMatch(value);
  }

  static bool passwordValidationPattern({required String value}) {
    String pattern =
        r'^(?=.*?[A-Z])(?=.*?[a-z])(?=.*?[0-9])(?=.*?[^\w\s]).{8,}$';
    RegExp regExp = RegExp(pattern);
    return !regExp.hasMatch(value);
  }

  static String removeAllHtmlTags(String htmlText) {
    RegExp exp = RegExp(r"<[^>]*>", multiLine: true, caseSensitive: true);

    return htmlText.replaceAll(exp, '').trim();
  }

  static String removeAMPFromString(String itemName) {
    return itemName.replaceAll(RegExp("amp;"), "").trim();
  }

  static String removeAllHtmlTagsAndAddWithDash(String htmlText) {
    RegExp exp = RegExp(r"<[^>]*>", multiLine: true, caseSensitive: true);

    return htmlText.replaceAll(exp, '');
  }

  static bool isContainHTMLTags(String text) {
    RegExp exp = RegExp(r"<[^>]*>", multiLine: true, caseSensitive: true);

    return exp.hasMatch(text);
  }

  static String removeOtherChatFromNumber(String numbers) {
    return numbers.replaceAll(RegExp('[^0-9]'), '');
  }

  static String autoGeneratePassword() {
    const base = AppConst.autoGeneratedPasswordBase;
    const randomLength = 6; // ONLY 6 characters generated
    const chars =
        'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!@#\$%^&*()';

    final random = Random.secure();

    return base +
        List.generate(
          randomLength,
              (_) => chars[random.nextInt(chars.length)],
        ).join();
  }

  static String getUserRoleName(String roleId) {
    switch (roleId) {
      case "1":
        return 'Admin';
      case "2":
        return 'Consultant';
      case "3":
        return 'Customer';
      default:
        return 'Unknown';
    }
  }

  static String getNCRStatus(String currentStatus) {
    switch (currentStatus) {
      case AppConst.openNCRStatusKey:
        return 'Open';
      case AppConst.inProgressNCRStatusKey:
        return 'In Progress';
      case AppConst.closedNCRStatusKey:
        return 'Closed';
      default:
        return 'Open';
    }
  }

  static Color getNCRStatusColor(String status) {
    switch (status) {
      case AppConst.openNCRStatusKey:
        return AppColors.orange;
      case AppConst.inProgressNCRStatusKey:
        return AppColors.blue;
      case AppConst.closedNCRStatusKey:
        return AppColors.green;
      default:
        return Colors.grey;
    }
  }

  static IconData getNCRStatusIcons(String status) {
    switch (status) {
      case  AppConst.openNCRStatusKey:
        return Icons.pending_actions;
      case AppConst.inProgressNCRStatusKey:
        return Icons.autorenew;
      case AppConst.closedNCRStatusKey:
        return Icons.check_circle;
      default:
        return  Icons.pending_actions;
    }
  }

  static bool isSuperAdmin(String? roleId) {
    switch (roleId) {
      case  AppConst.superAdminRole:
        return true;
      default:
        return false;
    }
  }

  static bool isAdmin(String? roleId) {
    switch (roleId) {
      case  AppConst.adminRole:
        return true;
      default:
        return false;
    }
  }

  static bool isConsultant(String? roleId) {
    switch (roleId) {
      case  AppConst.consultantRole:
        return true;
      default:
        return false;
    }
  }
  static bool isCustomer(String? roleId) {
    switch (roleId) {
      case  AppConst.customerRole:
        return true;
      default:
        return false;
    }
  }

  static String formatTimestamp(Timestamp? timestamp) {
    if(timestamp!=null)
    {
      final date = timestamp.toDate();
      return DateFormat('dd MMM yyyy').format(date);
    }else{
      return "";
    }
  }
}
